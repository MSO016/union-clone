    def load_settings(self):
        try:
            conn = sqlite3.connect('app/database/service_orders.db')
            cursor = conn.cursor()
            cursor.execute('\n                SELECT company_name, trading_name, cnpj, address, city, state,\n                       phone, email, website, logo, footer_message, warranty_text\n                FROM company_settings\n                WHERE user_id = ?\n                ORDER BY id DESC LIMIT 1\n            ', (self.user_id,))
            result = cursor.fetchone()
            if result:
                def convert_to_str(value):
                    if isinstance(value, bytes):
                        return value.decode('utf-8')
                    return value or ''
                self.company_name_edit.setText(convert_to_str(result[0]))
                self.trading_name_edit.setText(convert_to_str(result[1]))
                self.cnpj_edit.setText(convert_to_str(result[2]))
                self.address_edit.setText(convert_to_str(result[3]))
                self.city_edit.setText(convert_to_str(result[4]))
                self.state_edit.setText(convert_to_str(result[5]))
                self.phone_edit.setText(convert_to_str(result[6]))
                self.email_edit.setText(convert_to_str(result[7]))
                self.website_edit.setText(convert_to_str(result[8]))
                if result[9]:
                    self.logo_data = result[9]
                    pixmap = QPixmap()
                    pixmap.loadFromData(self.logo_data)
                    scaled_pixmap = pixmap.scaled(self.logo_label.size(), Qt.KeepAspectRatio, Qt.SmoothTransformation)
                    self.logo_label.setPixmap(scaled_pixmap)
                self.footer_message_edit.setText(convert_to_str(result[10]))
                self.warranty_input.setPlainText(convert_to_str(result[11]))
        except Exception as e:
            QMessageBox.warning(self, self.translation_manager.get_text('error'), f'{self.translation_manager.get_text('error_loading_settings')}: {str(e)}')
        if conn:
            conn.close()
    def save_settings(self):
        try:
            conn = sqlite3.connect('app/database/service_orders.db')
            cursor = conn.cursor()
            company_name = str(self.company_name_edit.text())
            trading_name = str(self.trading_name_edit.text())
            cnpj = str(self.cnpj_edit.text())
            address = str(self.address_edit.text())
            city = str(self.city_edit.text())
            state = str(self.state_edit.text())
            phone = str(self.phone_edit.text())
            email = str(self.email_edit.text())
            website = str(self.website_edit.text())
            footer_message = str(self.footer_message_edit.text())
            warranty_text = str(self.warranty_input.toPlainText())
            cursor.execute("\n                UPDATE company_settings \n                SET company_name = ?, trading_name = ?, cnpj = ?, address = ?, \n                    city = ?, state = ?, phone = ?, email = ?, website = ?, \n                    logo = ?, footer_message = ?, warranty_text = ?, \n                    updated_at = datetime('now', 'localtime')\n                WHERE user_id = ?\n            ", (company_name, trading_name, cnpj, address, city, state, phone, email, website, self.logo_data, footer_message, warranty_text, self.user_id))
            if cursor.rowcount == 0:
                cursor.execute('\n                    INSERT INTO company_settings (\n                        company_name, trading_name, cnpj, address, city, state,\n                        phone, email, website, logo, footer_message, warranty_text, user_id\n                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)\n                ', (company_name, trading_name, cnpj, address, city, state, phone, email, website, self.logo_data, footer_message, warranty_text, self.user_id))
            conn.commit()
            QMessageBox.information(self, self.translation_manager.get_text('success'), self.translation_manager.get_text('settings_saved'))
            self.accept()
        except Exception as e:
            QMessageBox.warning(self, self.translation_manager.get_text('error'), f'{self.translation_manager.get_text('error_saving_settings')}: {str(e)}')
        if conn:
            conn.close()
